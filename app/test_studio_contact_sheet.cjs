// node --test app/test_studio_contact_sheet.cjs
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');
const path = require('node:path');
const test = require('node:test');
const { openEditor } = require('./test_studio_editor.cjs');

test('authorized source frames page by measured shot, expire with consent and stay out of the saved edit', async () => {
  const ui = openEditor();
  await ui.ready();
  // Repeat Rafii's own timer footage in memory to exercise page two of the decoder.
  const input = path.join(__dirname, '../docs/creative-intelligence/examples/timer-study/reference.mp4');
  const repeat = spawnSync('ffmpeg', ['-v', 'error', '-stream_loop', '1', '-i', input, '-map', '0:v:0',
    '-c:v', 'libx264', '-preset', 'ultrafast', '-threads', '1', '-bf', '0', '-g', '240', '-movflags', 'frag_keyframe+empty_moov', '-f', 'mp4', 'pipe:1'], { maxBuffer: 4 * 1024 * 1024 });
  assert.equal(repeat.status, 0);
  const source = new File([repeat.stdout], 'Timer sequence.mp4');
  ui.get('reference-source').value = 'file';
  await ui.get('reference-source').fire('change');
  ui.get('reference-file').files = [source];
  await ui.get('reference-file').fire('change');
  ui.get('reference-rights').checked = true;
  await ui.submit('reference-form');
  assert.match(ui.get('notice').textContent, /Reference timing is ready/);
  assert(ui.state().reference.shots.length > 4);
  await ui.click('frames-toggle');
  assert.equal(ui.get('frames-toggle').getAttribute('aria-expanded'), 'true', ui.get('notice').textContent);
  assert.equal(ui.get('frame-options').children.length, 4);
  const sourceUrl = ui.get('frame-image').src;
  assert.match(sourceUrl, /^data:image\/jpeg;base64,/);
  assert.equal(Buffer.from(sourceUrl.split(',')[1], 'base64').readUInt16BE(0), 0xffd8);
  await ui.get('frame-options').children[1].fire('click');
  assert.match(ui.get('frame-caption').textContent, /^Shot 2 .*Decoded frame at [0-9.]+ s$/);
  assert.equal(ui.get('frame-direction').hidden, true);
  await ui.click('frames-next');
  assert.equal(ui.get('frames-page').textContent, 'Page 2 of 2');
  assert.match(ui.get('frame-caption').textContent, /^Shot 5 /);
  assert.equal(ui.get('frames-next').disabled, true);
  await ui.click('frames-prev');
  assert.equal(ui.get('frames-prev').disabled, true);
  ui.get('brief').value = 'Introduce an original desk timer.';
  await ui.get('brief-form').fire('input');
  await ui.click('blueprint');
  const first = ui.state().scenes[0];
  assert.equal(first.referenceSpan.sha256, ui.state().reference.sha256);
  assert.equal(ui.get('frame-direction').hidden, false);
  assert(ui.get('frame-direction').textContent.includes(first.direction));
  ui.get('frames-coverage').value = 'intervals';
  await ui.get('frames-coverage').fire('change');
  assert.match(ui.get('frame-caption').textContent, /^Interval 1 · 0–1 s · Decoded frame at /);
  assert.equal(ui.get('frames-page').textContent, 'Page 1 of 2');
  await ui.click('frames-next');
  assert.match(ui.get('frame-caption').textContent, /^Interval 5 · 4–5 s · Decoded frame at /);
  const pts = Number(ui.get('frame-caption').textContent.match(/at ([0-9.]+) s/)[1]) * 1000;
  const proposal = ui.state().scenes.find(s => s.referenceSpan.startMs <= pts && pts < s.referenceSpan.endMs);
  assert(ui.get('frame-direction').textContent.includes(proposal.direction));
  ui.get('frames-coverage').value = 'scenes';
  await ui.get('frames-coverage').fire('change');
  assert.match(ui.get('frame-caption').textContent, /^Shot 1 /);
  assert.equal(ui.get('frames-page').textContent, 'Page 1 of 2');
  await ui.click('save');
  const saved = await (await fetch(ui.downloads.at(-1).url)).text();
  assert(!saved.includes(sourceUrl.split(',')[1].slice(0, 64)));
  ui.get('reference-rights').checked = false;
  await ui.get('reference-rights').fire('change');
  assert.equal(ui.get('frames-toggle').disabled, true);
  assert.equal(ui.get('frames-content').hidden, true);
  assert.equal(ui.get('frame-image').hidden, true);
  assert.equal(ui.get('frame-options').children.length, 0);
  ui.get('reference-file').files = [new File([repeat.stdout], 'Another selection.mp4')];
  await ui.get('reference-file').fire('change');
  assert.equal(ui.get('reference-rights').checked, false);
  ui.get('open-file').files = [new File([saved], 'saved.rafii.json')];
  await ui.get('open-file').fire('change');
  assert.equal(ui.get('frames-toggle').disabled, true);
  assert.equal(ui.get('frame-image').hidden, true);
});

test('a continuous eight-second reference has one detected shot and a paginated time overview', async () => {
  const ui = openEditor();
  await ui.ready();
  const media = spawnSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=teal:size=160x90:rate=12:duration=8',
    '-c:v', 'libx264', '-threads', '1', '-bf', '0', '-g', '240', '-movflags', 'frag_keyframe+empty_moov', '-f', 'mp4', 'pipe:1']);
  assert.equal(media.status, 0);
  ui.get('reference-source').value = 'file';
  await ui.get('reference-source').fire('change');
  ui.get('reference-file').files = [new File([media.stdout], 'Uncut eight seconds.mp4')];
  await ui.get('reference-file').fire('change');
  ui.get('reference-rights').checked = true;
  await ui.submit('reference-form');
  assert.equal(ui.state().reference.shots.length, 1);
  await ui.click('frames-toggle');
  assert.equal(ui.get('frame-options').children.length, 1);
  ui.get('frames-coverage').value = 'intervals';
  await ui.get('frames-coverage').fire('change');
  assert.equal(ui.get('frame-options').children.length, 4);
  await ui.click('frames-next');
  await ui.get('frame-options').children[3].fire('click');
  assert.match(ui.get('frame-caption').textContent, /^Interval 8 · 7–8 s · Decoded frame at 7\.5 s$/);
  ui.get('reference-source').value = 'sample';
  await ui.get('reference-source').fire('change');
  assert.equal(ui.get('frames-coverage').disabled, true);
  assert.equal(ui.get('frame-options').children.length, 0);
  assert.equal(ui.get('frame-image').hidden, true);
});
